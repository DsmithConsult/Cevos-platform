BEGIN;

CREATE TABLE IF NOT EXISTS cevos_projects (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 120),
    status VARCHAR(40) NOT NULL DEFAULT 'Draft',
    vehicle_id VARCHAR(80) NOT NULL CHECK (length(btrim(vehicle_id)) BETWEEN 1 AND 80),
    battery_id VARCHAR(80) NOT NULL CHECK (length(btrim(battery_id)) BETWEEN 1 AND 80),
    motor_id VARCHAR(80) NOT NULL CHECK (length(btrim(motor_id)) BETWEEN 1 AND 80),
    range_miles INTEGER CHECK (range_miles BETWEEN 0 AND 2000),
    cost NUMERIC(12, 2) CHECK (cost BETWEEN 0 AND 10000000),
    battery_name VARCHAR(120),
    motor_name VARCHAR(120),
    power_kw INTEGER CHECK (power_kw BETWEEN 0 AND 5000),
    torque_nm INTEGER CHECK (torque_nm BETWEEN 0 AND 20000),
    readiness_score INTEGER CHECK (readiness_score BETWEEN 0 AND 100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_cevos_projects_updated_at CHECK (updated_at >= created_at)
);

CREATE INDEX IF NOT EXISTS ix_cevos_projects_updated_at
    ON cevos_projects (updated_at DESC);

COMMIT;